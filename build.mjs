// Bundles src/ into the single-file plugin.js that New API loads.
// node build.mjs          write plugin.js
// node build.mjs --check  fail when plugin.js is not the build of src/
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(fileURLToPath(import.meta.url));
// Dependency order; plugin.js is the entry and keeps its exports.
const MODULES = ["util.js", "ir.js", "systemone.js", "databricks.js", "extractions.js", "openai.js", "gemini.js", "vercel.js", "protocols.js", "channel.js", "models.js", "billing.js", "plugin.js"];

const HEADER = `// Decision — New API decision model gateway (task plugin, API v1).
// https://github.com/yiyinfaith/new-api-plugin-decision
// Copyright (C) 2026 yiyinfaith. Licensed under AGPL-3.0; see LICENSE.
// System One request validation is adapted from the official TypeSafe plugin
// (QuantumNous/new-api-plugins, plugins/tasks/typesafe, AGPL-3.0).
// Generated by build.mjs from src/; edit the sources, not this file.
`;

const IMPORT = /^import\s[\s\S]*?\sfrom\s+"\.\/[^"]+\.js";[ \t]*\r?\n/gm;
const DECLARATION = /^(?:export\s+)?(?:async\s+)?(?:function\*?|const|let|var|class)\s+([A-Za-z_$][\w$]*)/gm;

export function build() {
  const missing = readdirSync(join(root, "src")).filter((name) => name.endsWith(".js") && !MODULES.includes(name));
  if (missing.length) throw new Error("src/" + missing.join(", src/") + " is not in the bundle's module list");
  const seen = new Map();
  const chunks = [HEADER];
  for (const name of MODULES) {
    let source = readFileSync(join(root, "src", name), "utf8").replace(/\r\n/g, "\n");
    source = source.replace(IMPORT, "");
    if (/^import\s/m.test(source)) throw new Error(`${name}: only relative ./x.js imports can be bundled`);
    for (const match of source.matchAll(DECLARATION)) {
      if (seen.has(match[1])) throw new Error(`${name}: top-level name ${match[1]} is also declared in ${seen.get(match[1])}`);
      seen.set(match[1], name);
    }
    if (name !== "plugin.js") source = source.replace(/^export\s+(?=(?:async\s+)?(?:function|const|let|var|class)\b)/gm, "");
    if (/^export\s/m.test(source) && name !== "plugin.js") throw new Error(`${name}: unsupported export form`);
    chunks.push(`// ---- src/${name} ----\n` + source.trim() + "\n");
  }
  return chunks.join("\n");
}

// plugin.js at the root is the install file; marketplace/ is the release
// folder a plugin marketplace reads, with its own README and CHANGELOG.
const output = build();
const targets = [join(root, "plugin.js"), join(root, "marketplace", "plugin.js")];
if (process.argv.includes("--check")) {
  for (const target of targets) {
    let current = "";
    try {
      current = readFileSync(target, "utf8");
    } catch {}
    if (current !== output) {
      console.error(`${target} is out of date; run node build.mjs`);
      process.exit(1);
    }
  }
  console.log("plugin.js matches src/");
} else {
  for (const target of targets) writeFileSync(target, output);
  console.log(`wrote plugin.js (${output.length} bytes)`);
}
